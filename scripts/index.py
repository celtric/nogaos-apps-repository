#!/usr/bin/env python3
"""Writes index.html, the store's browseable front page, from the tree.

GitHub Pages serves the store as plain files, so its root would be a 404: this page lists every channel (each
catalogs/<channel>.json and the apps it currently offers) and every published jar under apps/<id>/<version>/, marking
which versions a channel lists now and which are history. It is generated by .github/workflows/index.yml on every push
that changes the tree and is never edited by hand. Standard library only, so the workflow needs no setup.
"""

import datetime
import html
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE_URL = "https://celtric.github.io/nogaos-apps-repository"

STYLE = """
body { margin: 0; background: #fafafa; color: #222; font: 15px/1.45 system-ui, -apple-system, "Segoe UI", Roboto,
  "Liberation Sans", sans-serif; }
main { max-width: 60em; margin: 0 auto; padding: 1em 16px 2em; }
h1 { font-size: 1.6em; margin: 0.4em 0; }
h2 { font-size: 1.3em; margin: 1.6em 0 0.4em; border-bottom: 1px solid #ddd; padding-bottom: 0.2em; }
h3 { font-size: 1.1em; margin: 1.2em 0 0.3em; }
a { color: #0645ad; }
code { font-family: ui-monospace, "Liberation Mono", Menlo, Consolas, monospace; font-size: 0.92em; }
.url { display: block; margin: 0.2em 0 0.6em; word-break: break-all; }
.url code { background: #fff; border: 1px solid #ddd; padding: 0.1em 0.3em; user-select: all; }
.scroll { overflow-x: auto; }
table { border-collapse: collapse; width: 100%; background: #fff; }
th, td { border: 1px solid #ddd; padding: 0.3em 0.5em; text-align: left; vertical-align: top; }
th { background: #f0f0f0; font-weight: 600; }
.error { color: #a00; }
.empty, footer { color: #666; }
footer { margin-top: 2em; font-size: 0.9em; }
"""


def esc(value: object) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def text_of(value: object) -> str:
    """A manifest's name or description: a plain string, or a map of language to text (English first)."""
    if isinstance(value, dict):
        for key in ("en", *value.keys()):
            if isinstance(value.get(key), str):
                return value[key]
        return ""
    return "" if value is None else str(value)


def version_key(version: str) -> tuple:
    return (0, int(version), "") if version.isdigit() else (1, 0, version)


def size_of(size: int) -> str:
    if size < 1024:
        return f"{size} B"
    if size < 1024 * 1024:
        return f"{size / 1024:.1f} KB"
    return f"{size / (1024 * 1024):.1f} MB"


def local_jar(url: str) -> "Path | None":
    """The tree's copy of a jar the store serves, when the URL points into this store and the file is here."""
    prefix = BASE_URL + "/"
    if not url.startswith(prefix):
        return None
    path = (ROOT / url[len(prefix):]).resolve()
    try:
        path.relative_to(ROOT)
    except ValueError:
        return None
    return path if path.is_file() else None


def read_catalogs() -> list:
    """Every catalog as (file name, url, display name, apps, error); a catalog that fails to read keeps its error."""
    catalogs = []
    for path in sorted((ROOT / "catalogs").glob("*.json")):
        url = f"{BASE_URL}/catalogs/{path.name}"
        try:
            root = json.loads(path.read_text(encoding="utf-8"))
            if not isinstance(root, dict):
                raise ValueError("not a JSON object")
            apps = root.get("apps", [])
            if not isinstance(apps, list):
                raise ValueError('"apps" is not a list')
            name = root.get("name") if isinstance(root.get("name"), str) and root.get("name") else path.stem
            catalogs.append((path.name, url, name, [app for app in apps if isinstance(app, dict)], None))
        except (OSError, ValueError) as error:
            catalogs.append((path.name, url, path.stem, [], str(error)))
    return catalogs


def jar_cell(app: dict) -> str:
    url = app.get("jar")
    if not isinstance(url, str) or not url:
        return ""
    label = url.rsplit("/", 1)[-1]
    cell = f'<a href="{esc(url)}">{esc(label)}</a>'
    local = local_jar(url)
    if local is not None:
        cell += f" ({esc(size_of(local.stat().st_size))})"
    return cell


def sha_cell(app: dict) -> str:
    sha = app.get("sha256")
    if not isinstance(sha, str) or not sha:
        return ""
    return f'<code title="{esc(sha)}">{esc(sha[:12])}</code>'


def channel_section(catalog: tuple) -> str:
    file_name, url, name, apps, error = catalog
    out = [f"<h3>{esc(name)}</h3>",
           f'<p class="url"><code>{esc(url)}</code> <a href="{esc(url)}">{esc(file_name)}</a></p>']
    if error is not None:
        out.append(f'<p class="error">This catalog could not be read: {esc(error)}</p>')
        return "\n".join(out)
    if not apps:
        out.append('<p class="empty">This catalog lists no apps.</p>')
        return "\n".join(out)
    out.append('<div class="scroll"><table>')
    out.append("<tr><th>Name</th><th>Id</th><th>Version</th><th>Author</th><th>Description</th>"
               "<th>Permissions</th><th>Minimum NoGaOS</th><th>Jar</th><th>SHA-256</th></tr>")
    for app in sorted(apps, key=lambda a: text_of(a.get("name")).lower()):
        permissions = app.get("permissions")
        permissions = ", ".join(str(p) for p in permissions) if isinstance(permissions, list) else ""
        out.append("<tr>" + "".join(f"<td>{cell}</td>" for cell in (
            esc(text_of(app.get("name"))), f"<code>{esc(app.get('id'))}</code>", esc(app.get("version")),
            esc(app.get("author")), esc(text_of(app.get("description"))), esc(permissions),
            esc(app.get("sdkVersion")), jar_cell(app), sha_cell(app))) + "</tr>")
    out.append("</table></div>")
    return "\n".join(out)


def versions_section(catalogs: list) -> str:
    listed = {}
    for _, _, name, apps, _ in catalogs:
        for app in apps:
            listed.setdefault((str(app.get("id")), str(app.get("version"))), []).append(name)
    jars = {}
    for jar in (ROOT / "apps").glob("*/*/*.jar"):
        if jar.is_file():
            jars.setdefault(jar.parent.parent.name, []).append(jar)
    if not jars:
        return '<p class="empty">No app versions published yet.</p>'
    out = []
    for app_id in sorted(jars):
        out.append(f"<h3><code>{esc(app_id)}</code></h3>")
        out.append('<div class="scroll"><table>')
        out.append("<tr><th>Version</th><th>Jar</th><th>Size</th><th>Listed by</th></tr>")
        for jar in sorted(jars[app_id], key=lambda j: (version_key(j.parent.name), j.name), reverse=True):
            version = jar.parent.name
            href = f"apps/{app_id}/{version}/{jar.name}"
            channels = ", ".join(sorted(listed.get((app_id, version), [])))
            out.append(f"<tr><td>{esc(version)}</td><td><a href=\"{esc(href)}\">{esc(jar.name)}</a></td>"
                       f"<td>{esc(size_of(jar.stat().st_size))}</td><td>{esc(channels)}</td></tr>")
        out.append("</table></div>")
    return "\n".join(out)


def commit() -> str:
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True,
                             check=True).stdout.strip()
        return sha or "working tree"
    except (OSError, subprocess.CalledProcessError):
        return "working tree"


def page() -> str:
    catalogs = read_catalogs()
    channels = "\n".join(channel_section(c) for c in catalogs) if catalogs else \
        '<p class="empty">No channels published yet.</p>'
    sha = commit()
    footer_sha = f"<code>{esc(sha)}</code>" if sha != "working tree" else "the working tree"
    date = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d") + " (UTC)"
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>NoGaOS apps repository</title>
<style>{STYLE}</style>
</head>
<body>
<main>
<h1>NoGaOS apps repository</h1>
<p>The published NoGaOS apps and the channel catalogs that list them; a computer subscribes to a channel by adding its \
catalog URL as a source in <strong>Applications</strong>.</p>
<h2>Channels</h2>
{channels}
<h2>All versions</h2>
{versions_section(catalogs)}
<footer>Generated on {esc(date)} from {"commit " if sha != "working tree" else ""}{footer_sha}.</footer>
</main>
</body>
</html>
"""


def main() -> None:
    try:
        (ROOT / "index.html").write_text(page(), encoding="utf-8", newline="\n")
    except OSError as error:
        print(f"index.py: cannot write index.html: {error}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
